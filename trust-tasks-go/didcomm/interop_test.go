package didcomm

import (
	"context"
	"encoding/hex"
	"encoding/json"
	"os"
	"testing"
	"time"

	tt "github.com/trustoverip/dtgwg-trust-tasks-tf/trust-tasks-go/trusttasks"
)

// The affinidi DIDComm library (affinidi-messaging-didcomm 0.15.8), which the
// Rust and Dart Trust Tasks DIDComm bindings are built on, packed this fixture
// with fixed X25519 keys. Unpacking it here proves the Go binding's ECDH-1PU
// authcrypt (tag-in-KDF, apv = SHA-256 of the recipient kids) is wire-compatible
// with the other two bindings — a JWE they produce, this binding opens.
//
// The fixture is regenerated by scripts/gen-didcomm-interop-fixture (a small
// Rust harness); see testdata/README or the DIDComm binding's README.

type interopFixture struct {
	JWE                 string `json:"jwe"`
	Plaintext           string `json:"plaintext"`
	SenderKid           string `json:"senderKid"`
	SenderPubX25519     string `json:"senderPubX25519"`
	RecipientKid        string `json:"recipientKid"`
	RecipientPrivX25519 string `json:"recipientPrivX25519"`
}

func TestInteropUnpacksAffinidiJWE(t *testing.T) {
	raw, err := os.ReadFile("testdata/authcrypt-interop.fixture.json")
	if err != nil {
		t.Fatal(err)
	}
	var f interopFixture
	if err := json.Unmarshal(raw, &f); err != nil {
		t.Fatal(err)
	}
	recipientPriv := mustHex(t, f.RecipientPrivX25519)
	senderPub := mustHex(t, f.SenderPubX25519)

	bob, err := NewIdentity(bareDID(f.RecipientKid), f.RecipientKid, recipientPriv)
	if err != nil {
		t.Fatal(err)
	}
	senderDID := bareDID(f.SenderKid)
	resolve := func(did string) (*PeerKey, error) {
		if did != senderDID {
			return nil, errUnknownSender(did)
		}
		return NewPeerKey(f.SenderKid, senderPub)
	}

	unpacked, err := UnpackTrustTask([]byte(f.JWE), bob, resolve)
	if err != nil {
		t.Fatalf("Go could not unpack the affinidi-packed JWE: %v", err)
	}

	// The authcrypt-verified sender and opening recipient.
	if unpacked.Transport.Peer != senderDID {
		t.Errorf("peer = %q, want %q", unpacked.Transport.Peer, senderDID)
	}
	if unpacked.Transport.Local != bareDID(f.RecipientKid) {
		t.Errorf("local = %q, want %q", unpacked.Transport.Local, bareDID(f.RecipientKid))
	}

	// The recovered Trust Task document (the DIDComm message body) matches what
	// affinidi sealed.
	var doc struct {
		Type    string `json:"type"`
		Payload struct {
			Text string `json:"text"`
		} `json:"payload"`
	}
	if err := json.Unmarshal(unpacked.Document, &doc); err != nil {
		t.Fatal(err)
	}
	if doc.Type != "https://trusttasks.org/spec/example/echo/0.1" {
		t.Errorf("document type = %q", doc.Type)
	}
	if doc.Payload.Text != "hello from affinidi" {
		t.Errorf("recovered payload text = %q, want %q", doc.Payload.Text, "hello from affinidi")
	}
}

// The full consumer path also runs over the affinidi-packed message.
func TestInteropConsumesAffinidiJWE(t *testing.T) {
	raw, _ := os.ReadFile("testdata/authcrypt-interop.fixture.json")
	var f interopFixture
	_ = json.Unmarshal(raw, &f)

	bob, err := NewIdentity(bareDID(f.RecipientKid), f.RecipientKid, mustHex(t, f.RecipientPrivX25519))
	if err != nil {
		t.Fatal(err)
	}
	senderPub := mustHex(t, f.SenderPubX25519)
	resolve := func(string) (*PeerKey, error) { return NewPeerKey(f.SenderKid, senderPub) }

	c := NewConsumer(bob)
	// The fixture's issuedAt is 2026-06-01; accept it.
	c.Now = func() time.Time { return time.Date(2026, 6, 1, 12, 0, 0, 0, time.UTC) }
	handler := func(_ context.Context, doc *tt.Document[echo], _ tt.ResolvedParties) (*tt.Document[echo], error) {
		return tt.RespondWith[echo, echo](doc, NewMessageID(), echo{Text: upper(doc.Payload.Text)}, nil), nil
	}
	got, err := Receive(context.Background(), c, []byte(f.JWE), resolve, echoSpec, decodeEcho, handler)
	if err != nil {
		t.Fatalf("receive affinidi JWE: %v", err)
	}
	if got.Outcome.Kind != tt.OutcomeHandled {
		t.Fatalf("outcome = %s, reply = %s", got.Outcome.Kind, got.Reply)
	}
	if got.Outcome.Response.Payload.Text != "HELLO FROM AFFINIDI" {
		t.Errorf("response = %q", got.Outcome.Response.Payload.Text)
	}
}

func mustHex(t *testing.T, s string) []byte {
	t.Helper()
	b, err := hex.DecodeString(s)
	if err != nil {
		t.Fatal(err)
	}
	return b
}

type unknownSenderError string

func (e unknownSenderError) Error() string { return "unknown sender " + string(e) }
func errUnknownSender(did string) error    { return unknownSenderError(did) }
