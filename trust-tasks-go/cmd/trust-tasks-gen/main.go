// Command trust-tasks-gen generates Go packages for the Trust Task
// specification versions an application pins in its trust-tasks.lock.
//
// An application locks the tasks it uses with the `trust-tasks` CLI, which
// vendors each version's registry bundle beside the lock. This command reads
// only those vendored files — no network, no Node, no checkout of the registry —
// verifies each against its locked digest, and writes one package per version:
//
//	//go:generate go run github.com/trustoverip/dtgwg-trust-tasks-tf/trust-tasks-go/cmd/trust-tasks-gen --lock trust-tasks.lock --out internal/tasks
//
// gives, for a lock pinning vault/get 0.3,
//
//	internal/tasks/vault/get/v0_3/payload.go   package vaultgetv0_3
//	internal/tasks/trusttasks.go               package tasks (ExtendsOf)
//
// imported as <your module>/internal/tasks/vault/get/v0_3. Every generated
// package imports only encoding/json and the trusttasks runtime, so the out
// directory may sit anywhere in the application's module and no import path
// needs to be configured. --package names the root package when the out
// directory's base name is not a valid one.
//
// Each package has the same shape as the prebuilt packages under
// trust-tasks-go/specs — Payload, Response, TypeURI, Spec, PayloadSchemaJSON, …
// — because it is generated by the same rules (an independent port of
// scripts/build-go-bindings.mjs, held to it by this command's equivalence test).
//
// The out directory is owned by the generator: rewritten whole on every run,
// and marked with a .trust-tasks-generated file. A non-empty directory without
// that marker is never cleared. The framework's own specifications
// (trust-task-*, trust-ceremony-*) are skipped: the trust-tasks-go module
// carries them, because the runtime speaks them.
//
// A task from a third-party source (a `[sources.<name>]` table in the lock,
// SPEC §6.5) is read from trust-tasks/@<name>/<slug>/<M.N>.bundle.json and
// generated under <out>/<name>/<slug>/v<M>_<N>, its TypeURI taken from the
// bundle. Note that the runtime's Type-URI parsing (SlugFromTypeURI, and so
// ReadForSpec / ReadForSpecWith / ExtendsChainReaches, ExtendedCode and
// FamilyCode) still accepts only https://trusttasks.org/spec/ URIs; ConsumeInbound
// and RespondWith do not parse the Type URI and work for a sourced task.
package main

import (
	"flag"
	"fmt"
	"os"
	"strings"
)

func main() {
	fs := flag.NewFlagSet("trust-tasks-gen", flag.ContinueOnError)
	lock := fs.String("lock", "trust-tasks.lock", "the application's `trust-tasks.lock`; bundles are read from trust-tasks/ beside it")
	out := fs.String("out", "", "the `directory` to generate into (required; owned by the generator)")
	pkg := fs.String("package", "", "the `name` of the root package in the out directory (default: derived from its base name)")
	fs.Usage = func() {
		fmt.Fprintln(fs.Output(), "usage: trust-tasks-gen --lock trust-tasks.lock --out <dir> [--package <name>]")
		fs.PrintDefaults()
	}
	if err := fs.Parse(os.Args[1:]); err != nil {
		os.Exit(2)
	}
	if *out == "" || fs.NArg() > 0 {
		fs.Usage()
		os.Exit(2)
	}
	if err := run(options{Lock: *lock, Out: *out, Package: *pkg}); err != nil {
		fmt.Fprintln(os.Stderr, "trust-tasks-gen:", err)
		os.Exit(1)
	}
}

func run(opts options) error {
	res, err := loadAndGenerate(opts)
	if err != nil {
		return err
	}
	if err := writeOut(opts.Out, opts.Lock, res); err != nil {
		return err
	}
	for _, n := range res.notes {
		fmt.Println("note:", n)
	}
	base := modulePathFor(opts.Out)
	count := 0
	for _, f := range res.files {
		if f.slug == "" {
			continue
		}
		count++
		where := f.rel
		if base != "" {
			where = base + "/" + strings.TrimSuffix(f.rel, "/payload.go")
		}
		fmt.Printf("  %s%s %s  →  %s (package %s)\n", sourceLabel(f.source), f.slug, f.version, where, f.pkg)
	}
	fmt.Printf("trust-tasks-gen: wrote %d package(s) to %s\n", count, opts.Out)
	return nil
}
