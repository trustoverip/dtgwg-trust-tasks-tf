// runtimeImport is the hand-written runtime every generated package imports,
// by module path — never by a relative path into it.
const runtimeImport = "github.com/trustoverip/dtgwg-trust-tasks-tf/trust-tasks-go/trusttasks"

// markerFile marks a directory as owned by this generator. A non-empty
// directory without it is never cleared.
const markerFile = ".trust-tasks-generated"

const markerText = "This directory is generated by trust-tasks-gen from trust-tasks.lock and the\n" +
	"bundles vendored beside it, and is rewritten whole on every run. Do not edit\n" +
	"it by hand: change the lock with `trust-tasks add` / `update` and regenerate.\n"

// officialPrefix is the official registry's authority. A Type URI under it is
// an official task's; anything else came from a third-party source.
const officialPrefix = "https://trusttasks.org/"

// frameworkSlug matches the framework's own specifications (SPEC §6.1's
// reserved namespace). The trust-tasks-go module already carries them as
// packages under specs/, because the runtime speaks them itself; generating a
// second copy into an application would give it two distinct Go types for one
// specification.
var frameworkSlug = regexp.MustCompile(`^trust-(task|ceremony)($|-|/)`)

// bundle is a registry bundle, `bundleVersion` 1
// (docs/design/consumer-side-generation.md, "Milestone 1").
type bundle struct {
	BundleVersion json.Number `json:"bundleVersion"`
	TypeURI       string      `json:"typeUri"`
	Slug          string      `json:"slug"`
	Version       string      `json:"version"`
	Status        string      `json:"status"`
	Deprecation   *string     `json:"deprecation"`
	Extends       *string     `json:"extends"`
	Policy        struct {
		Bearer            bool        `json:"bearer"`
		ProofRequired     variantBool `json:"proofRequired"`
		IssuedAtRequired  variantBool `json:"issuedAtRequired"`
		RecipientRequired variantBool `json:"recipientRequired"`
	} `json:"policy"`
	PropertyOrder  map[string][]string `json:"propertyOrder"`
	Schema         json.RawMessage     `json:"schema"`
	ResponseSchema json.RawMessage     `json:"responseSchema"`
}

type variantBool struct {
	Request  bool `json:"request"`
	Response bool `json:"response"`
}

// options configure one run.
type options struct {
	Lock    string // path to trust-tasks.lock
	Out     string // the directory the generator owns
	Package string // the root package's name; derived from Out when empty

	// includeFramework generates the framework's own specifications too. Only
	// the equivalence test sets it, to compare them with the prebuilt tree.
	includeFramework bool
}

// generated is one file to write, relative to the out directory.
type generated struct {
	rel     string
	code    []byte
	pkg     string
	source  string
	slug    string
	version string
}

// result is what a run produced, before anything is written.
type result struct {
	files []generated
	notes []string
}

// loadAndGenerate reads the lock and its vendored bundles, verifies every
// bundle against its locked digest, and renders the packages in memory.
// Nothing is written: a failure leaves the out directory as it was.
func loadAndGenerate(opts options) (*result, error) {
	text, err := os.ReadFile(opts.Lock)
	if err != nil {
		return nil, err
	}
	lock, err := parseLock(string(text))
	if err != nil {
		return nil, fmt.Errorf("%s is not a valid lockfile: %w", opts.Lock, err)
	}
	pkg := opts.Package
	if pkg == "" {
		pkg = derivePackageName(opts.Out)
	}
	if !regexp.MustCompile(`^[a-z][a-z0-9]*$`).MatchString(pkg) {
		return nil, fmt.Errorf("cannot derive a Go package name from --out %q; pass --package", opts.Out)
	}

	vendor := filepath.Join(filepath.Dir(opts.Lock), "trust-tasks")
	res := &result{}
	extends := map[string]string{}
	dirs := map[string]string{}
	for _, entry := range lock.Tasks {
		label := entry.Label() + " " + entry.Version
		if entry.Source == "" && frameworkSlug.MatchString(entry.Slug) && !opts.includeFramework {
			res.notes = append(res.notes, fmt.Sprintf(
				"%s: skipped — a framework specification; import it from %s/specs/%s/%s",
				label, strings.TrimSuffix(runtimeImport, "/trusttasks"), entry.Slug, versionDir(entry.Version)))
			continue
		}
		// A sourced task is vendored under `@<source>/`: `@` cannot begin a
		// slug, so it never collides with an official path.
		base := vendor
		if entry.Source != "" {
			base = filepath.Join(vendor, "@"+entry.Source)
		}
		path := filepath.Join(base, filepath.FromSlash(entry.Slug), entry.Version+".bundle.json")
		data, err := os.ReadFile(path)
		if err != nil {
			if errors.Is(err, os.ErrNotExist) {
				return nil, fmt.Errorf("%s: %s is missing — run `trust-tasks fetch`", label, path)
			}
			return nil, err
		}
		sum := sha256.Sum256(data)
		if "sha256:"+hex.EncodeToString(sum[:]) != entry.Digest {
			return nil, fmt.Errorf("%s: vendored bundle does not match trust-tasks.lock — run `trust-tasks check`", label)
		}
		var b bundle
		if err := json.Unmarshal(data, &b); err != nil {
			return nil, fmt.Errorf("%s: %s is not a bundle: %w", label, path, err)
		}
		if b.BundleVersion != "1" {
			return nil, fmt.Errorf("%s: bundleVersion %s; this trust-tasks-gen reads bundleVersion 1 — upgrade the trust-tasks-go module", label, b.BundleVersion)
		}
		if b.Slug != entry.Slug || b.Version != entry.Version || b.TypeURI != entry.TypeURI {
			return nil, fmt.Errorf("%s: the vendored bundle is %s %s (%s), not what trust-tasks.lock names", label, b.Slug, b.Version, b.TypeURI)
		}
		// Identity is the bundle's own Type URI. An official one lives under
		// trusttasks.org; a third-party one (SPEC §6.5) never does.
		official := strings.HasPrefix(b.TypeURI, officialPrefix)
		if entry.Source == "" && !official {
			return nil, fmt.Errorf("%s: an official task's Type URI %s is not under %s", label, b.TypeURI, officialPrefix)
		}
		if entry.Source != "" && official {
			return nil, fmt.Errorf("%s: a task from source `%s` has the official Type URI %s; official tasks take no `source`", label, entry.Source, b.TypeURI)
		}
		if b.Status == "withdrawn" {
			res.notes = append(res.notes, label+": skipped — withdrawn; nothing generated (move the pin with `trust-tasks update`)")
			continue
		}
		file, err := generatePackage(&b, entry.Source, entry.Digest)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", label, err)
		}
		dir := filepath.ToSlash(filepath.Dir(file.rel))
		if prior, clash := dirs[dir]; clash {
			return nil, fmt.Errorf("%s and %s would both generate into %s", prior, label, dir)
		}
		dirs[dir] = label
		res.files = append(res.files, file)
		if b.Extends != nil && *b.Extends != "" {
			extends[b.TypeURI] = *b.Extends
		}
	}

	root, err := renderRoot(pkg, extends)
	if err != nil {
		return nil, err
	}
	res.files = append(res.files, generated{rel: "trusttasks.go", code: root, pkg: pkg})
	sort.Slice(res.files, func(i, j int) bool { return res.files[i].rel < res.files[j].rel })
	return res, nil
}

// derivePackageName is the root package's default name: the out directory's
// base name, lowercased, with everything but letters and digits dropped.
func derivePackageName(out string) string {
	abs, err := filepath.Abs(out)
	if err != nil {
		abs = out
	}
	var b strings.Builder
	for _, r := range strings.ToLower(filepath.Base(abs)) {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') {
			b.WriteRune(r)
		}
	}
	return b.String()
}

// generatePackage renders one specification version's package.
//
// A task from a third-party source sits under a top-level directory named for
// the source — `<out>/acme/payments/settle/v1_0`, package
// acmepaymentssettlev1_0 — because a slug is unique only within its authority.
func generatePackage(b *bundle, source, digest string) (generated, error) {
	path := b.Slug
	if source != "" {
		path = source + "/" + b.Slug
	}
	for _, seg := range strings.Split(path, "/") {
		// The go command ignores `_`/`.`-prefixed directories and `testdata`:
		// a package there would be written and silently never built.
		if !slugPattern.MatchString(seg) || seg == "testdata" {
			return generated{}, fmt.Errorf("slug segment %q cannot be a Go package directory", seg)
		}
	}
	if !versionPattern.MatchString(b.Version) {
		return generated{}, fmt.Errorf("`%s` is not a MAJOR.MINOR version", b.Version)
	}

	parsed, err := decodeOrdered(b.Schema)
	if err != nil {
		return generated{}, fmt.Errorf("schema: %w", err)
	}
	schema, ok := parsed.(*object)
	if !ok {
		return generated{}, fmt.Errorf("schema is not a JSON object")
	}
	if err := applyPropertyOrder(schema, b.PropertyOrder); err != nil {
		return generated{}, err
	}

	defs, _ := schema.val("$defs").(*object)
	_, hasResponse := defs.get("Response")
	hasResponseSchema := len(b.ResponseSchema) > 0 && string(b.ResponseSchema) != "null"
	if hasResponse != hasResponseSchema {
		return generated{}, fmt.Errorf("bundle's responseSchema disagrees with its schema's $defs.Response")
	}

	em := newEmitter()
	defNames, rootName := em.emitDeclarations(schema, "Payload")
	deprecation := ""
	if b.Deprecation != nil {
		deprecation = *b.Deprecation
	}
	if deprecation != "" {
		markDeprecated(em.decls, rootName, deprecation)
		if hasResponse {
			markDeprecated(em.decls, defNames["#/$defs/Response"], deprecation)
		}
	}

	requestJSON, err := compact(b.Schema)
	if err != nil {
		return generated{}, err
	}
	responseJSON := ""
	if hasResponse {
		if responseJSON, err = compact(b.ResponseSchema); err != nil {
			return generated{}, err
		}
	}
	tail := emitTail(b, hasResponse, requestJSON, responseJSON, deprecation)

	pkg := goPackageName(path, b.Version)
	imports := []string{}
	if em.needsJSON {
		imports = append(imports, `"encoding/json"`)
	}
	imports = append(imports, goString(runtimeImport))

	header := []string{
		"// Code generated by trust-tasks-gen. DO NOT EDIT.",
		"// Source: " + sourceLabel(source) + b.Slug + "/" + b.Version + " bundle, " + digest,
		"",
		"package " + pkg,
	}
	if len(imports) == 1 {
		header = append(header, "", "import "+imports[0])
	} else {
		header = append(header, "", "import (")
		for _, i := range imports {
			header = append(header, "\t"+i)
		}
		header = append(header, ")")
	}
	body := strings.Join(append(append([]string{}, em.decls...), tail...), "\n\n")
	src := strings.Join(header, "\n") + "\n\n" + body + "\n"

	formatted, err := format.Source([]byte(src))
	if err != nil {
		return generated{}, fmt.Errorf("generated source does not parse: %w", err)
	}
	rel := filepath.ToSlash(filepath.Join(path, versionDir(b.Version), "payload.go"))
	return generated{rel: rel, code: formatted, pkg: pkg, source: source, slug: b.Slug, version: b.Version}, nil
}

func sourceLabel(source string) string {
	if source == "" {
		return ""
	}
	return source + ":"
}

func compact(raw json.RawMessage) (string, error) {
	var buf bytes.Buffer
	if err := json.Compact(&buf, raw); err != nil {
		return "", err
	}
	return buf.String(), nil
}

// applyPropertyOrder restores the authored order of every `properties` object
// in the request schema from the bundle's propertyOrder, and refuses an entry
// that names a different set of members or points nowhere.
func applyPropertyOrder(schema *object, order map[string][]string) error {
	used := map[string]bool{}
	var walk func(node any, ptr string) error
	walk = func(node any, ptr string) error {
		switch t := node.(type) {
		case *object:
			if names, ok := order[ptr]; ok {
				used[ptr] = true
				props, ok := t.val("properties").(*object)
				if !ok {
					return fmt.Errorf("propertyOrder %s: no properties there", ptr)
				}
				if len(names) != len(props.keys) {
					return fmt.Errorf("propertyOrder %s names %d members, the schema has %d", ptr, len(names), len(props.keys))
				}
				for _, n := range names {
					if _, ok := props.vals[n]; !ok {
						return fmt.Errorf("propertyOrder %s names %q, which the schema lacks", ptr, n)
					}
				}
				props.keys = append([]string(nil), names...)
			}
			for _, k := range t.keys {
				if err := walk(t.vals[k], ptr+"/"+escapePointer(k)); err != nil {
					return err
				}
			}
		case []any:
			for i, v := range t {
				if err := walk(v, fmt.Sprintf("%s/%d", ptr, i)); err != nil {
					return err
				}
			}
		}
		return nil
	}
	if err := walk(schema, "/schema"); err != nil {
		return err
	}
	for ptr := range order {
		if (ptr == "/schema" || strings.HasPrefix(ptr, "/schema/")) && !used[ptr] {
			return fmt.Errorf("propertyOrder %s points at no object in the schema", ptr)
		}
	}
	return nil
}

func escapePointer(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "~", "~0"), "/", "~1")
}

// emitTail is what every package carries after its types: the Type URIs, the
// lifecycle constants, the schemas and the SPEC §7.2 policy.
func emitTail(b *bundle, hasResponse bool, requestJSON, responseJSON, deprecation string) []string {
	typeURI := b.TypeURI
	extends := ""
	if b.Extends != nil {
		extends = *b.Extends
	}
	var out []string
	out = append(out, strings.Join([]string{
		"// TypeURI is the Trust Task type URI this package's Payload is carried under.",
		"const TypeURI = " + goString(typeURI),
	}, "\n"))
	out = append(out, strings.Join([]string{
		"// Extends is the MAJOR.MINOR of this specification that this version declares it",
		"// extends (SPEC §5.2 \"Declared extension\"), or \"\" when it declares none. A",
		"// consumer implementing that version may read this version's documents by",
		"// ignoring the payload members it does not recognise — see",
		"// trusttasks.ReadForSpec. The direct declaration only; the chain is walked",
		"// through the registry-wide index in package specs.",
		"const Extends = " + goString(extends),
	}, "\n"))
	out = append(out, strings.Join([]string{
		"// Deprecation is empty for a current specification version, and otherwise says",
		"// why this one is deprecated and what replaces it: \"superseded by <slug>/<M.N>\",",
		"// \"retired; use <slug>/<M.N>\" or \"retired\". A deprecated version is still",
		"// supported, but is withdrawn from this module in a later scheduled release.",
		"const Deprecation = " + goString(deprecation),
	}, "\n"))
	if hasResponse {
		out = append(out, strings.Join([]string{
			"// ResponseTypeURI is the success-response form of TypeURI (SPEC §4.4.1).",
			"const ResponseTypeURI = " + goString(typeURI+"#response"),
		}, "\n"))
	}
	out = append(out, strings.Join([]string{
		"// PayloadSchemaJSON is this specification's payload schema, as JSON text.",
		"//",
		"// SPEC §7.2 item 2 is performed against this. It ships with the package rather",
		"// than only as a file under specs/ because a Go struct carries none of the",
		"// schema's constraints — not minLength, not pattern, not the oneOf mutual",
		"// exclusion — so without it every such rule is unenforced. Cross-file $refs are",
		"// already inlined, so it needs no resolver.",
		"const PayloadSchemaJSON = " + goString(requestJSON),
	}, "\n"))
	if hasResponse {
		out = append(out, strings.Join([]string{
			"// ResponsePayloadSchemaJSON is PayloadSchemaJSON for the success-response variant.",
			"const ResponsePayloadSchemaJSON = " + goString(responseJSON),
		}, "\n"))
	}

	block := func(uriConst string, proof, recipient, issuedAt bool, schemaConst string) string {
		return strings.Join([]string{
			fmt.Sprintf("\tTypeURI:             %s,", uriConst),
			fmt.Sprintf("\tIsBearer:            %t,", b.Policy.Bearer),
			fmt.Sprintf("\tIsProofRequired:     %t,", proof),
			fmt.Sprintf("\tIsRecipientRequired: %t,", recipient),
			fmt.Sprintf("\tIsIssuedAtRequired:  %t,", issuedAt),
			fmt.Sprintf("\tPayloadSchema:       %s,", schemaConst),
		}, "\n")
	}
	p := b.Policy
	out = append(out, strings.Join([]string{
		"// Spec is the SPEC §7.2 policy for the request variant, taken from this",
		"// specification's front matter. Pass it to trusttasks.ConsumeInbound — items 5b,",
		"// 7 and 8 are per-specification and cannot be derived from the document alone,",
		"// and item 2 needs the schema it carries.",
		"var Spec = trusttasks.SpecPolicy{",
		block("TypeURI", p.ProofRequired.Request, p.RecipientRequired.Request, p.IssuedAtRequired.Request, "PayloadSchemaJSON"),
		"}",
	}, "\n"))
	if hasResponse {
		out = append(out, strings.Join([]string{
			"// ResponseSpec is the SPEC §7.2 policy for the success-response variant.",
			"// IsRecipientRequired tracks the *issuer* party's requirement, because a response",
			"// swaps the parties (§7.3 item 5).",
			"var ResponseSpec = trusttasks.SpecPolicy{",
			block("ResponseTypeURI", p.ProofRequired.Response, p.RecipientRequired.Response, p.IssuedAtRequired.Response, "ResponsePayloadSchemaJSON"),
			"}",
		}, "\n"))
	}
	return out
}

// renderRoot is the out directory's own package: the locked versions' declared
// extensions, as a trusttasks.ExtendsLookup.
func renderRoot(pkg string, extends map[string]string) ([]byte, error) {
	uris := make([]string, 0, len(extends))
	for u := range extends {
		uris = append(uris, u)
	}
	sort.Strings(uris)
	lines := []string{
		"// Code generated by trust-tasks-gen. DO NOT EDIT.",
		"",
		"// Package " + pkg + " holds the Trust Task specification versions pinned in",
		"// trust-tasks.lock: one package per version beneath this directory, at",
		"// <slug>/v<MAJOR>_<MINOR>, each importing only the trusttasks runtime.",
		"package " + pkg,
		"",
		"import (",
		"\t\"strings\"",
		"",
		"\t" + goString(runtimeImport),
		")",
		"",
		"// extendsIndex maps the bare Type URI of each locked version that declares an",
		"// extension (SPEC §5.2 \"Declared extension\") to the MAJOR.MINOR it extends.",
		"var extendsIndex = map[string]string{",
	}
	for _, u := range uris {
		lines = append(lines, "\t"+goString(u)+": "+goString(extends[u])+",")
	}
	lines = append(lines,
		"}",
		"",
		"// ExtendsOf is a trusttasks.ExtendsLookup over the locked versions' declarations,",
		"// falling back to trusttasks.RegistryExtends for versions this application did",
		"// not lock. Pass it to trusttasks.ReadForSpecWith so a document of a newer version",
		"// that declares it extends a locked one is read as the locked one.",
		"func ExtendsOf(typeURI string) string {",
		"\tif i := strings.IndexByte(typeURI, '#'); i >= 0 {",
		"\t\ttypeURI = typeURI[:i]",
		"\t}",
		"\tif v, ok := extendsIndex[typeURI]; ok {",
		"\t\treturn v",
		"\t}",
		"\treturn trusttasks.RegistryExtends(typeURI)",
		"}",
		"",
		"var _ trusttasks.ExtendsLookup = ExtendsOf",
	)
	return format.Source([]byte(strings.Join(lines, "\n") + "\n"))
}

// writeOut replaces the out directory's contents with res. A non-empty
// directory without the marker is refused, so a mistyped --out cannot delete
// someone's source.
func writeOut(out, lockPath string, res *result) error {
	absOut, err := filepath.Abs(out)
	if err != nil {
		return err
	}
	absLock, err := filepath.Abs(lockPath)
	if err != nil {
		return err
	}
	if lockDir := filepath.Dir(absLock); lockDir == absOut || strings.HasPrefix(lockDir, absOut+string(filepath.Separator)) {
		return fmt.Errorf("--out %s contains trust-tasks.lock; generate into a directory of its own", out)
	}
	entries, err := os.ReadDir(absOut)
	switch {
	case errors.Is(err, os.ErrNotExist):
	case err != nil:
		return err
	case len(entries) > 0:
		if _, err := os.Stat(filepath.Join(absOut, markerFile)); err != nil {
			return fmt.Errorf("refusing to clear %s: it is not empty and has no %s marker, so this generator did not write it", out, markerFile)
		}
		for _, e := range entries {
			if err := os.RemoveAll(filepath.Join(absOut, e.Name())); err != nil {
				return err
			}
		}
	}
	if err := os.MkdirAll(absOut, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(absOut, markerFile), []byte(markerText), 0o644); err != nil {
		return err
	}
	for _, f := range res.files {
		path := filepath.Join(absOut, filepath.FromSlash(f.rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, f.code, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// modulePathFor finds the go.mod enclosing dir and returns the import path dir
// has in that module, or "" when there is none.
func modulePathFor(dir string) string {
	abs, err := filepath.Abs(dir)
	if err != nil {
		return ""
	}
	for d := abs; ; d = filepath.Dir(d) {
		if data, err := os.ReadFile(filepath.Join(d, "go.mod")); err == nil {
			for _, line := range strings.Split(string(data), "\n") {
				f := strings.Fields(line)
				if len(f) >= 2 && f[0] == "module" {
					rel, err := filepath.Rel(d, abs)
					if err != nil {
						return ""
					}
					mod := strings.Trim(f[1], `"`)
					if rel == "." {
						return mod
					}
					return mod + "/" + filepath.ToSlash(rel)
				}
			}
			return ""
		}
		if filepath.Dir(d) == d {
			return ""
		}
	}
}
