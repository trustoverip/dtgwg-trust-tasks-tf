package main

// The equivalence test: generate every bundle in the registry and compare the
// result with the prebuilt packages under trust-tasks-go/specs, which
// scripts/build-go-bindings.mjs generates from the specs/ tree.
//
// It needs the registry's bundles, which the Rust codegen builds:
//
//	cargo run -q --release -p trust-tasks-codegen -- --bundles /tmp/registry
//	TRUST_TASKS_BUNDLES=/tmp/registry go test ./cmd/trust-tasks-gen -run Equivalence -v
//
// and is skipped without them. What it holds the two generators to:
//
//   - Every prebuilt payload package has a generated twin, and vice versa,
//     except trust-task-error (no bundle: every runtime models it by hand) and
//     withdrawn versions (neither generator emits one).
//   - The package clause and imports are byte-identical.
//   - Every top-level declaration is byte-identical — doc comment, type, every
//     field in order — except PayloadSchemaJSON / ResponsePayloadSchemaJSON,
//     whose doc comments are byte-identical and whose values are JSON-equal.
//   - The declarations come in the same order: the bundle's `defsOrder`
//     restores the order the prebuilt generator declares `$defs` types in.
//   - The whole file is byte-identical once the two header lines and the
//     embedded schema literals are masked — nothing between declarations
//     differs either.
//   - The extends index holds the same entries as specs/extends.go.
//
// The differences it permits, and why:
//
//  1. The first two lines (`// Code generated by …` and `// Source: …`) name
//     this generator and the bundle instead of the .mjs and the schema file.
//  2. The embedded schema text is key-sorted. A bundle's schema is JCS, and
//     propertyOrder restores the authored order of `properties` only, so the
//     JSON text cannot be byte-identical; it is JSON-equal.
//  3. Shared-schema packages (specs/<x>/shared/…, specs/framework/…) have no
//     counterpart: a bundle inlines what its payload reaches, and so does each
//     prebuilt payload package, so nothing imports them.

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"testing"
)

type indexFile struct {
	Specs []struct {
		TypeURI string `json:"typeUri"`
		Slug    string `json:"slug"`
		Version string `json:"version"`
		Status  string `json:"status"`
		Digest  string `json:"digest"`
		Path    string `json:"path"`
	} `json:"specs"`
	Excluded []struct {
		Slug string `json:"slug"`
	} `json:"excluded"`
}

func TestEquivalenceWithPrebuiltTree(t *testing.T) {
	registry := os.Getenv("TRUST_TASKS_BUNDLES")
	if registry == "" {
		t.Skip("TRUST_TASKS_BUNDLES is not set (see the comment at the top of this file)")
	}
	prebuilt, err := filepath.Abs("../../specs")
	if err != nil {
		t.Fatal(err)
	}

	// A lock naming every version in the registry, with the bundles vendored
	// beside it in the layout an application has.
	var index indexFile
	data, err := os.ReadFile(filepath.Join(registry, "index.json"))
	if err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(data, &index); err != nil {
		t.Fatal(err)
	}
	app := t.TempDir()
	var lock strings.Builder
	lock.WriteString("version = 1\nregistry = \"https://trusttasks.org\"\n")
	for _, s := range index.Specs {
		fmt.Fprintf(&lock, "\n[[task]]\nslug = %q\nversion = %q\ntype_uri = %q\ndigest = %q\n", s.Slug, s.Version, s.TypeURI, s.Digest)
		b, err := os.ReadFile(filepath.Join(registry, filepath.FromSlash(s.Path)))
		if err != nil {
			t.Fatal(err)
		}
		dst := filepath.Join(app, "trust-tasks", filepath.FromSlash(s.Slug), s.Version+".bundle.json")
		if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(dst, b, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	lockPath := filepath.Join(app, "trust-tasks.lock")
	if err := os.WriteFile(lockPath, []byte(lock.String()), 0o644); err != nil {
		t.Fatal(err)
	}

	res, err := loadAndGenerate(options{Lock: lockPath, Out: filepath.Join(app, "gen"), Package: "gen", includeFramework: true})
	if err != nil {
		t.Fatal(err)
	}
	// Determinism: a second run is byte-identical.
	again, err := loadAndGenerate(options{Lock: lockPath, Out: filepath.Join(app, "gen"), Package: "gen", includeFramework: true})
	if err != nil {
		t.Fatal(err)
	}
	if len(again.files) != len(res.files) {
		t.Fatalf("second run produced %d files, first %d", len(again.files), len(res.files))
	}
	for i := range res.files {
		if res.files[i].rel != again.files[i].rel || !bytes.Equal(res.files[i].code, again.files[i].code) {
			t.Fatalf("second run differs at %s", res.files[i].rel)
		}
	}

	generatedByRel := map[string][]byte{}
	for _, f := range res.files {
		if f.slug != "" {
			generatedByRel[f.rel] = f.code
		}
	}

	excluded := map[string]bool{}
	for _, e := range index.Excluded {
		excluded[e.Slug] = true
	}
	prebuiltByRel := map[string][]byte{}
	skippedExcluded := 0
	err = filepath.Walk(prebuilt, func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() || info.Name() != "payload.go" {
			return err
		}
		rel, _ := filepath.Rel(prebuilt, path)
		rel = filepath.ToSlash(rel)
		slug := rel[:strings.LastIndex(rel[:strings.LastIndex(rel, "/")], "/")]
		if excluded[slug] {
			skippedExcluded++
			return nil
		}
		src, err := os.ReadFile(path)
		prebuiltByRel[rel] = src
		return err
	})
	if err != nil {
		t.Fatal(err)
	}

	var failures []string
	fail := func(format string, args ...any) { failures = append(failures, fmt.Sprintf(format, args...)) }

	for rel := range prebuiltByRel {
		if _, ok := generatedByRel[rel]; !ok {
			fail("%s: prebuilt, but not generated from any bundle", rel)
		}
	}
	rels := make([]string, 0, len(generatedByRel))
	for rel := range generatedByRel {
		if _, ok := prebuiltByRel[rel]; !ok {
			fail("%s: generated, but there is no prebuilt package", rel)
			continue
		}
		rels = append(rels, rel)
	}
	sort.Strings(rels)

	var identical, schemaTextDiffers int
	for _, rel := range rels {
		d := compareFiles(prebuiltByRel[rel], generatedByRel[rel])
		for _, f := range d.failures {
			fail("%s: %s", rel, f)
		}
		if len(d.failures) == 0 {
			identical++
		}
		schemaTextDiffers += d.schemaTextDiffers
	}

	// The extends index.
	want := extendsEntries(t, filepath.Join(prebuilt, "extends.go"))
	var root []byte
	for _, f := range res.files {
		if f.slug == "" {
			root = f.code
		}
	}
	got := map[string]string{}
	for _, m := range regexp.MustCompile(`(?m)^\t("[^"]+"): ("[^"]*"),$`).FindAllSubmatch(root, -1) {
		k, _ := strconv.Unquote(string(m[1]))
		v, _ := strconv.Unquote(string(m[2]))
		got[k] = v
	}
	for k, v := range want {
		if got[k] != v {
			fail("extends index: %s is %q in specs/extends.go, %q generated", k, v, got[k])
		}
	}
	for k := range got {
		if _, ok := want[k]; !ok {
			fail("extends index: %s generated, absent from specs/extends.go", k)
		}
	}

	t.Logf("%d bundles; %d payload packages compared (%d prebuilt trust-task-error packages have no bundle)",
		len(index.Specs), len(rels), skippedExcluded)
	t.Logf("byte-identical apart from the header and the schema text: %d", identical)
	t.Logf("schema constants JSON-equal but not byte-identical (permitted difference 2): %d", schemaTextDiffers)
	t.Logf("extends index: %d entries, equal", len(want))
	if len(failures) > 0 {
		sort.Strings(failures)
		if len(failures) > 50 {
			t.Errorf("%d unexplained differences; the first 50:", len(failures))
			failures = failures[:50]
		}
		for _, f := range failures {
			t.Error(f)
		}
	}
}

type fileDiff struct {
	failures          []string
	schemaTextDiffers int
}

type decl struct {
	key  string // what identifies it: "type X", "const X", "var X", "const (X…)"
	text string
}

// compareFiles holds a generated file to its prebuilt twin.
func compareFiles(want, got []byte) fileDiff {
	var d fileDiff
	wh, wd, err := splitFile(want)
	if err != nil {
		d.failures = append(d.failures, "prebuilt: "+err.Error())
		return d
	}
	gh, gd, err := splitFile(got)
	if err != nil {
		d.failures = append(d.failures, "generated: "+err.Error())
		return d
	}
	if wh != gh {
		d.failures = append(d.failures, fmt.Sprintf("package clause or imports differ:\n%s\n---\n%s", wh, gh))
	}
	reportedOrder := false
	byKey := map[string]decl{}
	for _, x := range gd {
		byKey[x.key] = x
	}
	if len(wd) != len(gd) {
		d.failures = append(d.failures, fmt.Sprintf("%d declarations prebuilt, %d generated", len(wd), len(gd)))
	}
	for i, w := range wd {
		g, ok := byKey[w.key]
		if !ok {
			d.failures = append(d.failures, "missing declaration "+w.key)
			continue
		}
		if i < len(gd) && gd[i].key != w.key && !reportedOrder {
			reportedOrder = true
			d.failures = append(d.failures, fmt.Sprintf("declaration %d is %s prebuilt, %s generated", i, w.key, gd[i].key))
		}
		if w.key == "const PayloadSchemaJSON" || w.key == "const ResponsePayloadSchemaJSON" {
			if w.text == g.text {
				continue
			}
			d.schemaTextDiffers++
			if msg := compareSchemaConst(w.text, g.text); msg != "" {
				d.failures = append(d.failures, w.key+": "+msg)
			}
			continue
		}
		if w.text != g.text {
			d.failures = append(d.failures, fmt.Sprintf("%s differs:\n--- prebuilt\n%s\n--- generated\n%s", w.key, w.text, g.text))
		}
	}
	// Whatever the declarations do not cover — blank lines, stray comments
	// between them — must match too.
	if len(d.failures) == 0 && !bytes.Equal(maskFile(want), maskFile(got)) {
		d.failures = append(d.failures, "the files differ outside their declarations")
	}
	return d
}

// schemaLiteral is an embedded schema constant's value, on one line.
var schemaLiteral = regexp.MustCompile(`(?m)^(const (?:Response)?PayloadSchemaJSON = )".*"$`)

// maskFile drops the two header lines (permitted difference 1) and replaces
// the embedded schema literals (permitted difference 2, compared as JSON
// above) with a placeholder.
func maskFile(src []byte) []byte {
	for i := 0; i < 2; i++ {
		if nl := bytes.IndexByte(src, '\n'); nl >= 0 {
			src = src[nl+1:]
		}
	}
	return schemaLiteral.ReplaceAll(src, []byte(`${1}"…"`))
}

// compareSchemaConst: the doc comments byte-identical, the JSON values equal.
func compareSchemaConst(want, got string) string {
	wDoc, wVal, ok1 := strings.Cut(want, "\nconst ")
	gDoc, gVal, ok2 := strings.Cut(got, "\nconst ")
	if !ok1 || !ok2 || wDoc != gDoc {
		return "doc comment differs"
	}
	parse := func(s string) (any, error) {
		_, lit, _ := strings.Cut(s, " = ")
		text, err := strconv.Unquote(lit)
		if err != nil {
			return nil, err
		}
		return decodeOrdered([]byte(text))
	}
	wj, err := parse(wVal)
	if err != nil {
		return "prebuilt: " + err.Error()
	}
	gj, err := parse(gVal)
	if err != nil {
		return "generated: " + err.Error()
	}
	if !jsonEqual(wj, gj) {
		return "schemas are not JSON-equal"
	}
	return ""
}

// splitFile returns the package clause and imports as text, and every
// top-level declaration (with its doc comment) as text, in file order.
func splitFile(src []byte) (string, []decl, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "", src, parser.ParseComments)
	if err != nil {
		return "", nil, err
	}
	offset := func(p token.Pos) int { return fset.Position(p).Offset }
	var head strings.Builder
	head.WriteString("package " + f.Name.Name + "\n")
	var decls []decl
	for _, dl := range f.Decls {
		gd, ok := dl.(*ast.GenDecl)
		if !ok {
			return "", nil, fmt.Errorf("unexpected function declaration")
		}
		start := gd.Pos()
		if gd.Doc != nil {
			start = gd.Doc.Pos()
		}
		text := string(src[offset(start):offset(gd.End())])
		if gd.Tok == token.IMPORT {
			head.WriteString(string(src[offset(gd.Pos()):offset(gd.End())]) + "\n")
			continue
		}
		var names []string
		for _, s := range gd.Specs {
			switch s := s.(type) {
			case *ast.TypeSpec:
				names = append(names, s.Name.Name)
			case *ast.ValueSpec:
				for _, n := range s.Names {
					names = append(names, n.Name)
				}
			}
		}
		decls = append(decls, decl{key: gd.Tok.String() + " " + strings.Join(names, ","), text: text})
	}
	return head.String(), decls, nil
}

// extendsEntries reads the entries of the prebuilt specs/extends.go.
func extendsEntries(t *testing.T, path string) map[string]string {
	t.Helper()
	src, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	out := map[string]string{}
	for _, m := range regexp.MustCompile(`(?m)^\t("[^"]+"): ("[^"]*"),$`).FindAllSubmatch(src, -1) {
		k, _ := strconv.Unquote(string(m[1]))
		v, _ := strconv.Unquote(string(m[2]))
		out[k] = v
	}
	if len(out) == 0 && !bytes.Contains(src, []byte("var extendsIndex = map[string]string{}")) {
		t.Fatalf("no entries read from %s, and it is not the empty index", path)
	}
	return out
}
