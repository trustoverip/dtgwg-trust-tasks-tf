// The driver behind `dart run trust_tasks:generate`: lock + vendored bundles in,
// a directory of Dart libraries out. See bin/generate.dart for the CLI and
// docs/design/consumer-side-generation.md for the model.

import 'dart:convert';
import 'dart:io';

import 'emit.dart';
import 'lock.dart';
import 'sha256.dart';

/// The marker a generated output directory carries. The generator refuses to
/// clear a non-empty directory without it, so `--out lib` cannot wipe an
/// application's sources.
const String markerFileName = '.trust-tasks-generated';

const String _markerText =
    'This directory is written by `dart run trust_tasks:generate` from\n'
    'trust-tasks.lock and the bundles vendored beside it. It is rewritten whole\n'
    'on every run, so do not edit anything in it.\n';

/// The language version generated code is formatted at: this package's SDK
/// floor, as `scripts/build-dart-bindings.mjs` formats the prebuilt tree.
const String defaultLanguageVersion = '3.3';

/// Specifications the runtime package already carries, generated by the
/// prebuilt tree under `package:trust_tasks/specs/`: the framework's own
/// (SPEC §6.1's reserved `trust-task-*` / `trust-ceremony-*` namespace).
final RegExp frameworkSlug = RegExp(r'^trust-(task|ceremony)($|-|/)');

/// Every official task's Type URI is this followed by `<slug>/<M.N>`.
const String registryTypeUriPrefix = 'https://trusttasks.org/spec/';

/// Why generation stopped.
class GenerateError implements Exception {
  GenerateError(this.message);
  final String message;
  @override
  String toString() => message;
}

/// What a run did.
class GenerateResult {
  GenerateResult(this.generated, this.notes);

  /// Output paths, relative to the output directory, of generated libraries.
  final List<String> generated;

  /// One line per task skipped, and why.
  final List<String> notes;
}

/// Read [lockPath] and its vendored bundles, verify every bundle against its
/// locked digest, and write the libraries into [outDir], replacing it whole.
Future<GenerateResult> generate({
  required String lockPath,
  required String outDir,
  String languageVersion = defaultLanguageVersion,
  String? dartExecutable,
}) async {
  final lockFile = File(lockPath);
  if (!lockFile.existsSync()) throw GenerateError('no lockfile at $lockPath');
  final Lockfile lock;
  try {
    lock = Lockfile.parse(lockFile.readAsStringSync());
  } on LockError catch (e) {
    throw GenerateError('$lockPath: $e');
  }
  final lockDir = lockFile.absolute.parent.path;

  // Verify everything before writing anything.
  final files = <String, String>{}; // relative path -> unformatted source
  final notes = <String>[];
  final extendsEntries = <(String, String)>[];
  final sources = <String, String>{};

  // A third-party task's libraries sit under a directory named for its source,
  // so a source may not share a name with an official task's first segment.
  for (final task in lock.tasks.where((t) => t.source != null)) {
    final namespace = dartFileName(task.source!);
    for (final official in lock.tasks.where((t) => t.source == null)) {
      final first = official.slug.split('/').first;
      if (first == task.source || dartFileName(first) == namespace) {
        throw GenerateError(
          'source `${task.source}` (${task.label}) has the name of the official '
          'task ${official.label}\'s first segment `$first`, so their libraries '
          'would share $namespace/ — rename the source in trust-tasks.toml',
        );
      }
    }
  }

  for (final task in lock.tasks) {
    final rel = task.bundlePath;
    if (task.source != null && frameworkSlug.hasMatch(task.slug)) {
      throw GenerateError(
        '${task.label}: a framework specification (trust-task-*, '
        'trust-ceremony-*) cannot come from a third-party source (SPEC §6.5)',
      );
    }
    final file = File('$lockDir/$rel');
    if (!file.existsSync()) {
      throw GenerateError(
        'no vendored bundle for ${task.label} at $rel — '
        'run `trust-tasks check`',
      );
    }
    final bytes = file.readAsBytesSync();
    final actual = sha256Digest(bytes);
    if (actual != task.digest) {
      throw GenerateError(
        'vendored bundle does not match trust-tasks.lock — run `trust-tasks check` '
        '($rel: the lock pins ${task.digest}, the file is $actual)',
      );
    }
    final Bundle bundle;
    try {
      bundle = Bundle.parse(utf8.decode(bytes));
    } on Object catch (e) {
      throw GenerateError('$rel: $e');
    }
    if (bundle.slug != task.slug ||
        bundle.version != task.version ||
        bundle.typeUri != task.typeUri) {
      throw GenerateError(
        '$rel is the bundle of ${bundle.typeUri}, but trust-tasks.lock pins it '
        'as ${task.typeUri}',
      );
    }
    // The Type URI is the identity the generated library carries, so its
    // authority must match where the lock says the task came from.
    if (task.source == null) {
      final expected = '$registryTypeUriPrefix${bundle.slug}/${bundle.version}';
      if (bundle.typeUri != expected) {
        throw GenerateError(
          '$rel: an official task\'s Type URI must be $expected, not '
          '${bundle.typeUri} — a task from another authority needs a source',
        );
      }
    } else if (bundle.typeUri.startsWith('https://trusttasks.org/')) {
      throw GenerateError(
        '$rel: ${bundle.typeUri} is a registry Type URI, but the lock takes it '
        'from source `${task.source}` — pin it without a source',
      );
    }

    if (bundle.isWithdrawn) {
      notes.add('${task.label}: withdrawn — nothing generated '
          '(move the pin with `trust-tasks update`)');
      continue;
    }
    if (frameworkSlug.hasMatch(task.slug)) {
      notes.add('${task.label}: a framework specification — '
          'import package:trust_tasks/specs/'
          '${libraryPathFor(task.slug, task.version)} instead');
      continue;
    }

    final path =
        libraryPathFor(bundle.slug, bundle.version, source: task.source);
    final previous = sources[path];
    if (previous != null) {
      throw GenerateError('$rel and $previous both generate $path — two slugs '
          'snake_case to the same Dart path');
    }
    sources[path] = rel;
    try {
      files[path] = generateLibrary(bundle, source: '$rel (${task.digest})');
    } on BundleError catch (e) {
      throw GenerateError('$rel: $e');
    }
    if (bundle.extendsVersion != null) {
      extendsEntries.add((bundle.typeUri, bundle.extendsVersion!));
    }
  }
  if (files.containsKey('extends_index.dart')) {
    throw GenerateError('a task library would occupy extends_index.dart');
  }
  files['extends_index.dart'] = generateExtendsIndex(extendsEntries);

  // Write and format in a staging directory, so a failure leaves the output
  // directory as it was, and formatting cannot pick up an application's own
  // formatter settings (the output is the same in every application).
  final staging = Directory.systemTemp.createTempSync('trust-tasks-generate-');
  try {
    for (final entry in files.entries) {
      final f = File('${staging.path}/${entry.key}');
      f.parent.createSync(recursive: true);
      f.writeAsStringSync(entry.value);
    }
    final dart = dartExecutable ?? _dartExecutable();
    ProcessResult format(List<String> flags) {
      try {
        return Process.runSync(dart, ['format', ...flags, staging.path]);
      } on ProcessException catch (e) {
        throw GenerateError('could not run `$dart format`: ${e.message}');
      }
    }

    // `--language-version` pins the style: since Dart 3.7 the formatter picks
    // it from the code's language version, and a directory outside any package
    // would otherwise get the newest ("tall") one. An SDK older than the flag
    // has only the one style the flag would select, so it is dropped there.
    var formatted = format(['--language-version=$languageVersion']);
    if (formatted.exitCode == 64 &&
        '${formatted.stderr}'.contains('language-version')) {
      formatted = format(const []);
    }
    if (formatted.exitCode != 0) {
      throw GenerateError(
          'dart format failed:\n${formatted.stderr}${formatted.stdout}');
    }

    _replaceOutput(outDir, staging, files.keys);
  } finally {
    staging.deleteSync(recursive: true);
  }

  final generated = files.keys.where((p) => p != 'extends_index.dart').toList()
    ..sort();
  return GenerateResult(generated, notes);
}

/// The `dart` this program runs on, so formatting uses the same SDK.
String _dartExecutable() {
  final exe = Platform.resolvedExecutable;
  final base = exe.split(Platform.pathSeparator).last;
  return base == 'dart' || base == 'dart.exe' ? exe : 'dart';
}

void _replaceOutput(String outDir, Directory staging, Iterable<String> paths) {
  final out = Directory(outDir);
  if (out.existsSync()) {
    final entries = out.listSync();
    if (entries.isNotEmpty && !File('$outDir/$markerFileName').existsSync()) {
      throw GenerateError(
        '$outDir is not empty and has no $markerFileName marker — refusing to '
        'replace a directory this generator did not write. Point --out at an '
        'empty or generated directory.',
      );
    }
    for (final entry in entries) {
      entry.deleteSync(recursive: true);
    }
  } else {
    out.createSync(recursive: true);
  }
  for (final rel in paths) {
    final target = File('$outDir/$rel');
    target.parent.createSync(recursive: true);
    File('${staging.path}/$rel').copySync(target.path);
  }
  File('$outDir/$markerFileName').writeAsStringSync(_markerText);
}
