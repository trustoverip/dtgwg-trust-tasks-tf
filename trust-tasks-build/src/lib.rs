//! Generate the Rust types for the Trust Tasks an application uses, at build
//! time, from the registry bundles it has vendored.
//!
//! An application pins the specification versions it speaks in
//! `trust-tasks.lock` (written by the `trust-tasks` CLI), with each version's
//! registry bundle vendored beside it under `trust-tasks/`. Its build script
//! runs this crate:
//!
//! ```no_run
//! // build.rs
//! fn main() -> Result<(), trust_tasks_build::Error> {
//!     trust_tasks_build::Config::new() // ./trust-tasks.lock + ./trust-tasks/
//!         .compile()?;                // writes $OUT_DIR/trust_tasks_generated.rs
//!     Ok(())
//! }
//! ```
//!
//! and includes the result:
//!
//! ```ignore
//! mod tasks {
//!     include!(concat!(env!("OUT_DIR"), "/trust_tasks_generated.rs"));
//! }
//!
//! use tasks::vault::upsert::v0_4::{Payload, Response};
//! ```
//!
//! The module path of each version is the one `trust_tasks_rs::specs` gives
//! it (`<family>::<task>::v<M>_<N>`, hyphens as underscores), and its contents
//! are what `trust_tasks_rs::specs` carries for that version, generated by the
//! same code: the `Payload`/`Response` types and builders, their
//! `trust_tasks_rs::Payload` impls with the version's policy constants,
//! `EXTENDS`, `DEPRECATION` and `ERROR_CODES`.
//!
//! # Third-party sources
//!
//! A lockfile may also pin specifications from a third-party source — a
//! specification under another authority than `https://trusttasks.org` (SPEC
//! §6.5), vendored at `trust-tasks/@<source>/<slug>/<M.N>.bundle.json`. Each
//! source's tasks sit under a top-level module named for it, so the source
//! `acme`'s `payments/settle` 1.0 is `tasks::acme::payments::settle::v1_0`,
//! beside the registry's families. Identity is always the bundle's Type URI,
//! so a sourced `vault/get` and the registry's `vault/get` are different types
//! with different `TYPE_URI`s, and never route into each other. A source named
//! like an official family in the same lock is refused, as is a sourced bundle
//! claiming the registry's authority, or one with a framework slug.
//!
//! # Dependencies of the generated code
//!
//! The generated code names the runtime as `::trust_tasks_rs`, and serde,
//! serde_json, regress and chrono through `trust_tasks_rs::__private`, so an
//! application needs exactly two dependencies — `trust-tasks-rs` (with
//! `default-features = false` to leave out the prebuilt specification
//! modules) and this crate as a build dependency.
//!
//! # What is checked
//!
//! Every bundle is verified against the digest the lockfile pins before
//! anything is generated, and must name the slug, version and Type URI it is
//! locked as. A mismatch stops the build: "vendored bundle does not match
//! trust-tasks.lock — run `trust-tasks check`". No network is used.
//!
//! # Declared extension
//!
//! The generated file ends with an `EXTENDS` table and a `declare_extends()`
//! function. Calling it once registers the locked versions' SPEC §5.2
//! `extends` chains with the runtime, so its dispatchers route a document of a
//! locked version to the handler of a registered version it extends — the
//! runtime's own table only knows the registry as of its release.

