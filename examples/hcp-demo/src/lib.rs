// ── Deterministic inputs ───────────────────────────────────────────────────
// A fixed clock the demo controls: it starts at START and moves one second per
// document issued. The system time is never read.
pub const START: &str = "2026-11-25T10:00:00Z";

/// An instant as the documents write it: whole seconds, `YYYY-MM-DDTHH:MM:SSZ`.
/// The repository's rule is "never write `Utc::now()` into a document": every
/// instant the demo writes comes from its injected [`Clock`], which holds whole
/// seconds only, and goes through this one function.
pub fn iso(t: DateTime<Utc>) -> String {
    t.to_rfc3339_opts(SecondsFormat::Secs, true)
}

/// The demo's clock, shared by every party (and the proof verifier).
#[derive(Clone)]
pub struct Clock(Arc<AtomicI64>);

impl Clock {
    fn new() -> Self {
        let start = DateTime::parse_from_rfc3339(START).expect("START is RFC 3339");
        Self(Arc::new(AtomicI64::new(start.timestamp())))
    }

    pub fn now(&self) -> DateTime<Utc> {
        DateTime::from_timestamp(self.0.load(Ordering::SeqCst), 0).expect("in range")
    }

    /// Now, as an instant.
    pub fn iso(&self) -> String {
        iso(self.now())
    }

    /// `seconds` after now, as an instant.
    pub fn plus(&self, seconds: i64) -> String {
        iso(self.now() + TimeDelta::seconds(seconds))
    }

    /// One second on: the instant of the next document issued.
    pub fn tick(&self) -> DateTime<Utc> {
        self.0.fetch_add(1, Ordering::SeqCst);
        self.now()
    }

    /// Let time pass without issuing a document (a client waiting out
    /// `retryAfter`, or a test).
    pub fn advance(&self, seconds: i64) {
        self.0.fetch_add(seconds, Ordering::SeqCst);
    }
}

/// Sequential urn:uuid identifiers: …-000000000001, …-000000000002, …
#[derive(Clone, Default)]
pub struct Ids(Arc<AtomicU64>);

impl Ids {
    pub fn next(&self) -> String {
        let n = self.0.fetch_add(1, Ordering::SeqCst) + 1;
        format!("urn:uuid:00000000-0000-4000-8000-{n:012x}")
    }
}

// ── Parties ────────────────────────────────────────────────────────────────
// DEMO ONLY keys: each is 32 bytes of one repeated value. Never use such keys
// for anything real. The VID is the did:key of the Ed25519 signing key, and
// the same VID names the party in TSP.
pub struct Party {
    pub name: &'static str,
    pub vid: String,
    signer: Secret,
    tsp: PrivateVid,
}

fn party(name: &'static str, signing_seed: u8, encryption_seed: u8) -> Party {
    let seed = [signing_seed; 32]; // DEMO ONLY
    let public = Secret::generate_ed25519(None, Some(&seed))
        .get_public_keymultibase()
        .expect("ed25519 public multikey");
    let vid = format!("did:key:{public}");
    let vm = format!("{vid}#{public}");
    let mut signer = Secret::generate_ed25519(Some(&vm), Some(&seed));
    signer.id = vm;
    let tsp = PrivateVid::from_keys(vid.clone(), seed, [encryption_seed; 32]); // DEMO ONLY
    Party {
        name,
        vid,
        signer,
        tsp,
    }
}

