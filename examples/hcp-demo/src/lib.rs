//! The Human Context Protocol (HCP) carried as Trust Tasks, end to end, in one
//! process. A DEMONSTRATION, not a reference provider: see README.md and
//! `examples/hcp-demo-ts/SCENARIO.md` (the language-neutral script every port
//! of this demo follows, with the golden transcript they all print).
//!
//! Three parties, each with its own did:key and TSP keys:
//!   - the HCP Provider (a toy, in-memory: a few entries, a client registry,
//!     a grant table);
//!   - a Context Client (a booking agent that wants the person's context);
//!   - a Management Client (the person's own app, which can revoke grants).
//!
//! Every document is signed with `trust_tasks::proof` (eddsa-jcs-2022), sealed
//! with `trust_tasks::tsp` (a Direct TSP message: HPKE-Auth, signed), opened,
//! and run through the SPEC §7.2 pipeline (proof verified over the document as
//! received, payload validated against its schema with a JSON Schema 2020-12
//! validator) before anything acts on it. Nothing touches the network.
//!
//! It is laid out as an application is: `trust-tasks.lock` pins the four
//! `hcp/*` tasks, `build.rs` generates them with `trust-tasks-build`, and the
//! framework tasks it also speaks (`trust-task-discovery`,
//! `trust-task-next-step`) ship with the runtime.

