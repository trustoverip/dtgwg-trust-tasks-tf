// A signed acl/grant/0.3 round trip over HTTP, both ends in one process — the
// Go twin of examples/getting-started (Rust).
//
//	go generate ./... && go run .
//
// This is the worked example behind §3a of GETTING-STARTED.md at the repo
// root. The regions marked GETTING-STARTED:begin/end below are extracted
// verbatim into that document, and scripts/check-getting-started-snippets.mjs
// fails if the file and the document disagree — so the snippets a newcomer
// copies are code that compiles and runs, not code that once did.
//
// It is laid out as an application is: trust-tasks.lock pins the one task it
// speaks, and `go generate` runs trust-tasks-gen, which checks the vendored
// bundle against its locked digest and writes the package into internal/tasks
// (committed, as go generate output usually is; CI regenerates it and fails on
// drift). The proofs come from the trust-tasks-go/proof module. There is no Go
// HTTPS package, so the receiver is a net/http handler speaking the HTTPS
// binding's wire format (bindings/https): POST /trust-tasks, a bearer token
// naming the sender, and the binding's status mapping.
package main

//go:generate go run github.com/trustoverip/dtgwg-trust-tasks-tf/trust-tasks-go/cmd/trust-tasks-gen --lock trust-tasks.lock --out internal/tasks

