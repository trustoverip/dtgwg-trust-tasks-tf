// sender is the producing end: build the document, sign it, send it, read the
// reply. It returns the signed document it sent.
func sender(signer *proof.Signer, serverURL string) (json.RawMessage, error) {
	// acl/grant/0.3 states every authority axis explicitly — there is no
	// default and no implicit form. Carol may act everywhere, may use no keys,
	// holds the full ceiling of the `moderator` role, and may use what she
	// reads for any purpose (`any` never includes `modelTraining`). The scope
	// unions are oneOf in the schema, so they generate as json.RawMessage.
	label, reason := "Carol — content moderation", "onboarding moderator"
	payload := grant.Payload{
		Entry: grant.ACLEntry{
			Subject:      "did:web:carol.example",
			Role:         "moderator",
			Act:          json.RawMessage(`{"scope":"all"}`),
			Keys:         json.RawMessage(`{"scope":"none"}`),
			Capabilities: json.RawMessage(`{"scope":"ceiling"}`),
			Purposes:     json.RawMessage(`{"scope":"any"}`),
			Label:        &label,
		},
		Reason: &reason,
	}

	// TRAP: party members and issuedAt must be set BEFORE signing — a member
	// added after the fact is one the proof does not cover, and the receiver
	// refuses the document as proofInvalid.
	recipient, issuedAt := serverVID, tt.SystemClock() // whole seconds, UTC
	unsigned, err := json.Marshal(tt.Document[grant.Payload]{
		ID:        newID(),
		Type:      grant.TypeURI,
		Issuer:    &signer.DID, // the *signing* identity, which the bearer token maps to
		Recipient: &recipient,
		IssuedAt:  &issuedAt,
		Payload:   payload,
	})
	if err != nil {
		return nil, err
	}
	request, err := signer.Sign(unsigned, proof.SignOptions{})
	if err != nil {
		return nil, err
	}

	var sent tt.Document[grant.Payload]
	_ = json.Unmarshal(request, &sent)
	fmt.Printf("  [client] POST /trust-tasks  id=%s\n", sent.ID)

	req, _ := http.NewRequest(http.MethodPost, serverURL+"/trust-tasks", bytes.NewReader(request))
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Authorization", "Bearer alice")
	res, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, err
	}
	defer res.Body.Close()
	body, err := io.ReadAll(res.Body)
	if err != nil {
		return nil, err
	}

	if res.StatusCode == http.StatusOK {
		var resp tt.Document[grant.Response]
		if err := json.Unmarshal(body, &resp); err != nil {
			return nil, err
		}
		fmt.Printf("  [client] ← %s\n           threadId=%s entry: subject=%s role=%s\n",
			resp.Type, *resp.ThreadID, resp.Payload.Entry.Subject, resp.Payload.Entry.Role)
	} else {
		var refusal tt.ErrorResponse
		if err := json.Unmarshal(body, &refusal); err != nil {
			return nil, fmt.Errorf("HTTP %d", res.StatusCode)
		}
		fmt.Printf("  [client] ← HTTP %d trust-task-error: code=%s retryable=%t\n",
			res.StatusCode, refusal.Payload.Code, refusal.Payload.Retryable)
	}
	return request, nil
}

// GETTING-STARTED:end sender

// post sends doc as-is and returns the HTTP status and the body.
func post(serverURL string, doc []byte) (int, []byte, error) {
	req, _ := http.NewRequest(http.MethodPost, serverURL+"/trust-tasks", bytes.NewReader(doc))
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Authorization", "Bearer alice")
	res, err := http.DefaultClient.Do(req)
	if err != nil {
		return 0, nil, err
	}
	defer res.Body.Close()
	body, err := io.ReadAll(res.Body)
	return res.StatusCode, body, err
}

// expectRefusal posts doc and checks it is refused with code under status.
func expectRefusal(serverURL string, doc []byte, status int, code string) error {
	got, body, err := post(serverURL, doc)
	if err != nil {
		return err
	}
	var refusal tt.ErrorResponse
	if err := json.Unmarshal(body, &refusal); err != nil || got != status || refusal.Payload.Code != code {
		return fmt.Errorf("expected HTTP %d %s, got HTTP %d %s", status, code, got, body)
	}
	return nil
}

func main() {
	log.SetFlags(0)
	if err := run(); err != nil {
		log.Fatalf("getting-started-go: %v", err)
	}
	fmt.Println("getting-started-go: round trip, retry, tamper and schema checks all OK")
}

func run() error {
	signer := demoIdentity()
	listener, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		return err
	}
	server := &http.Server{Handler: receiver(signer.DID), ReadHeaderTimeout: 5 * time.Second}
	go func() { _ = server.Serve(listener) }()
	defer server.Close()
	serverURL := "http://" + listener.Addr().String()
	fmt.Printf("  [server] listening on %s/trust-tasks (vid %s)\n", serverURL, serverVID)

	// 1. The round trip the document walks through.
	request, err := sender(signer, serverURL)
	if err != nil {
		return err
	}
	var sent tt.Document[grant.Payload]
	if err := json.Unmarshal(request, &sent); err != nil {
		return err
	}

	// 2. The same bytes again: §7.2 item 11 absorbs the retry and returns the
	//    first execution's response — the handler does not run a second time.
	status, body, err := post(serverURL, request)
	if err != nil {
		return err
	}
	var retried tt.Document[grant.Response]
	if err := json.Unmarshal(body, &retried); err != nil || status != http.StatusOK ||
		retried.Type != grant.ResponseTypeURI || retried.ThreadID == nil || *retried.ThreadID != sent.ID {
		return fmt.Errorf("retry: HTTP %d %s", status, body)
	}
	fmt.Println("  [client] retry absorbed: same response, handler not re-run")

	// 3. A payload changed after signing: the proof no longer covers it.
	tampered := bytes.Replace(request, []byte(`"role":"moderator"`), []byte(`"role":"owner"`), 1)
	tampered = bytes.Replace(tampered, []byte(sent.ID), []byte(newID()), 1)
	if err := expectRefusal(serverURL, tampered, http.StatusUnprocessableEntity, "proofInvalid"); err != nil {
		return fmt.Errorf("tampered: %w", err)
	}
	fmt.Println("  [client] tampered copy refused: proofInvalid")

	// 4. A payload the schema refuses, correctly signed: item 2 catches it.
	invalid := sent
	invalid.ID, invalid.Proof = newID(), nil
	issuedAt := tt.SystemClock()
	invalid.IssuedAt = &issuedAt
	invalid.Payload.Entry.Purposes = nil
	unsigned, err := json.Marshal(invalid)
	if err != nil {
		return err
	}
	unsigned = bytes.Replace(unsigned, []byte(`,"purposes":null`), nil, 1)
	signed, err := signer.Sign(unsigned, proof.SignOptions{})
	if err != nil {
		return err
	}
	if err := expectRefusal(serverURL, signed, http.StatusBadRequest, "malformedRequest"); err != nil {
		return fmt.Errorf("schema: %w", err)
	}
	fmt.Println("  [client] payload missing `purposes` refused: malformedRequest")
	return nil
}
