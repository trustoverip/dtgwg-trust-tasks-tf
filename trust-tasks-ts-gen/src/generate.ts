/**
 * Lockfile + vendored bundles → an output directory of TypeScript modules.
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

import { readLockedBundle, type Bundle } from "./bundle.js";
import { emitExtendsIndex, emitIndex, emitSourceIndex, generateModule, type GeneratedModule } from "./emit.js";
import { parseLock, taskLabel, type LockedTask } from "./lock.js";

/** The file that marks a directory as this generator's to rewrite. */
export const MARKER_FILE = ".trust-tasks-generated";

const MARKER_TEXT =
  "This directory is generated by trust-tasks-gen-ts (@openvtc/trust-tasks-gen) from\n" +
  "trust-tasks.lock and the bundles vendored beside it. It is rewritten whole on every\n" +
  "run: do not edit it, and do not put anything else in it.\n";

/**
 * Specifications the runtime (`@openvtc/trust-tasks`) carries itself: the
 * framework's reserved namespace (SPEC §6.1, `trust-task-*` / `trust-ceremony-*`
 * — `trust-task-error`, `-discovery`, `-next-step`, `-ok`, `trust-ceremony-receipt`, …).
 * The runtime speaks them, so an application never generates them a second time.
 */
const FRAMEWORK_SLUG = /^trust-(task|ceremony)($|-|\/)/;

export function isFrameworkSlug(slug: string): boolean {
  return FRAMEWORK_SLUG.test(slug);
}

export interface GenerateOptions {
  /** The lockfile. Bundles are read from `<dir of lock>/trust-tasks/`. */
  lock: string;
  /** The output directory, owned by the generator. */
  out: string;
  /** Where notes go (skips, counts). Defaults to stderr. */
  log?: (line: string) => void;
  /**
   * Generate framework specifications too. Only the repository's equivalence
   * test sets this — an application gets them from the runtime.
   * @internal
   */
  includeFramework?: boolean;
}

export interface GenerateResult {
  /** Paths written, relative to `out`, sorted. */
  readonly files: readonly string[];
  /** The modules generated. */
  readonly modules: readonly GeneratedModule[];
  /** `slug/M.N` → why it was not generated. */
  readonly skipped: ReadonlyMap<string, string>;
}

/**
 * Generate in memory: verify every bundle against the lock, then emit a module
 * per generated version plus `index.ts` and `_extends.ts`. Writes nothing.
 * Throws on the first bundle that does not verify — nothing is generated from
 * a lock whose bundles disagree with it.
 */
export async function generateFiles(
  options: Pick<GenerateOptions, "lock" | "log" | "includeFramework">,
): Promise<{ files: Map<string, string>; modules: GeneratedModule[]; skipped: Map<string, string> }> {
  const log = options.log ?? ((line: string) => process.stderr.write(`${line}\n`));
  const lock = parseLock(readFileSync(options.lock, "utf8"));
  const bundleDir = path.join(path.dirname(path.resolve(options.lock)), "trust-tasks");

  // Verify everything before generating anything.
  const bundles: { task: LockedTask; bundle: Bundle }[] = lock.tasks.map((task) => ({
    task,
    bundle: readLockedBundle(bundleDir, task),
  }));

  // A source's modules live under a top-level directory (and namespace) named
  // for it, so it must not be the first segment of an official slug.
  const officialRoots = new Map<string, string>();
  for (const { task } of bundles) {
    if (task.source === null) officialRoots.set(task.slug.split("/")[0]!, taskLabel(task));
  }
  for (const { task } of bundles) {
    if (task.source === null) continue;
    const clash = officialRoots.get(task.source);
    if (clash !== undefined) {
      throw new Error(
        `source "${task.source}" (${taskLabel(task)}) has the same name as the first segment of the official task ${clash}; ` +
          `both would be generated under ${task.source}/ — rename the source in trust-tasks.toml`,
      );
    }
    // SPEC §6.5 item 2: the framework's reserved namespace is never private.
    if (isFrameworkSlug(task.slug)) {
      throw new Error(
        `${taskLabel(task)}: a framework specification (trust-task-* / trust-ceremony-*) cannot come from a third-party source`,
      );
    }
  }

  const skipped = new Map<string, string>();
  const modules: GeneratedModule[] = [];
  for (const { task, bundle } of bundles) {
    const id = taskLabel(task);
    if (bundle.status === "withdrawn") {
      skipped.set(id, "withdrawn — nothing is generated for a withdrawn version; move the pin with `trust-tasks update`");
      continue;
    }
    if (isFrameworkSlug(task.slug) && !options.includeFramework) {
      skipped.set(id, "a framework specification — @openvtc/trust-tasks carries it; nothing generated");
      continue;
    }
    try {
      modules.push(await generateModule(bundle, task.source));
    } catch (err) {
      throw new Error(`${id}: ${(err as Error).message}`);
    }
  }
  for (const [id, why] of skipped) log(`note: ${id}: ${why}`);

  modules.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  const files = new Map<string, string>();
  for (const m of modules) files.set(m.path, m.text);
  files.set("_extends.ts", emitExtendsIndex(modules));
  files.set("index.ts", emitIndex(modules));
  for (const source of new Set(modules.map((m) => m.source))) {
    if (source !== null) files.set(`${source}/index.ts`, emitSourceIndex(source, modules));
  }
  files.set(MARKER_FILE, MARKER_TEXT);
  return { files, modules, skipped };
}

/**
 * Empty `out` for a fresh write — refusing a non-empty directory that does not
 * carry the marker, so a mistyped `--out` cannot wipe a source tree.
 */
function claimOutDir(out: string): void {
  if (!existsSync(out)) {
    mkdirSync(out, { recursive: true });
    return;
  }
  if (!statSync(out).isDirectory()) throw new Error(`--out ${out} exists and is not a directory`);
  const entries = readdirSync(out);
  if (entries.length === 0) return;
  if (!entries.includes(MARKER_FILE)) {
    throw new Error(
      `refusing to overwrite ${out}: it is not empty and has no ${MARKER_FILE} marker, so it was not written by ` +
        `this generator. Point --out at an empty or generated directory.`,
    );
  }
  for (const entry of entries) rmSync(path.join(out, entry), { recursive: true, force: true });
}

/** Generate and write the output directory whole. */
export async function generate(options: GenerateOptions): Promise<GenerateResult> {
  const { files, modules, skipped } = await generateFiles(options);
  const out = path.resolve(options.out);
  claimOutDir(out);
  for (const [rel, text] of files) {
    const file = path.join(out, ...rel.split("/"));
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, text, "utf8");
  }
  const log = options.log ?? ((line: string) => process.stderr.write(`${line}\n`));
  log(`trust-tasks-gen-ts: ${modules.length} module(s) written to ${options.out}`);
  return { files: [...files.keys()].sort(), modules, skipped };
}
